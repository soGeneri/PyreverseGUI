import subprocess
import os
import shutil
import tempfile
from pathlib import Path
import json


class DiagramGenerator:
    def __init__(self):
        self.output_dir = "dist"
        self.ensure_output_dir()

    def ensure_output_dir(self):
        """Ensure the output directory exists"""
        os.makedirs(self.output_dir, exist_ok=True)

    def generate_diagram(
        self,
        project_path,
        output_format,
        diagram_type,
        output_name="diagram",
        options=None,
    ):
        """Generate UML diagram using pyreverse"""
        if options is None:
            options = {}

        # Prepare command
        cmd = ["python", "-m", "pylint.pyreverse"]

        # Add output directory
        output_path = os.path.join(self.output_dir, output_name)
        cmd.extend(["-o", output_format.lower().replace(".", "")])
        cmd.extend(["-p", output_name])

        # Add options
        cmd.extend(self._build_options(options))

        # Add diagram type options
        if diagram_type == "classes":
            cmd.append("-c")
        elif diagram_type == "packages":
            cmd.append("-p")
        # Both is default behavior

        # Add project path
        cmd.append(project_path)

        try:
            # Change to output directory
            original_cwd = os.getcwd()
            os.chdir(self.output_dir)

            # Execute pyreverse command
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)

            # Return to original directory
            os.chdir(original_cwd)

            if result.returncode == 0:
                # Find generated files
                generated_files = self._find_generated_files(output_name, output_format)

                return {
                    "success": True,
                    "files": generated_files,
                    "command": " ".join(cmd),
                    "output": result.stdout,
                    "message": "Diagram generated successfully",
                }
            else:
                return {
                    "success": False,
                    "error": result.stderr or result.stdout,
                    "command": " ".join(cmd),
                    "message": "Failed to generate diagram",
                }

        except subprocess.TimeoutExpired:
            return {
                "success": False,
                "error": "Command timed out",
                "message": "Diagram generation took too long",
            }
        except Exception as e:
            return {
                "success": False,
                "error": str(e),
                "message": "Unexpected error occurred",
            }

    def _build_options(self, options):
        """Build command line options from options dict"""
        cmd_options = []

        # Diagram options
        diagram_opts = options.get("diagram_options", {})
        if diagram_opts.get("show_ancestors", 0) > 0:
            cmd_options.extend(["-a", str(diagram_opts["show_ancestors"])])

        if diagram_opts.get("show_associated", 0) > 0:
            cmd_options.extend(["-s", str(diagram_opts["show_associated"])])

        if diagram_opts.get("show_builtin", False):
            cmd_options.append("-b")

        if diagram_opts.get("module_names", False):
            cmd_options.append("-m")

        if diagram_opts.get("only_classnames", False):
            cmd_options.append("-k")

        # Filter options
        filter_opts = options.get("filter_options", {})
        if filter_opts.get("ignore_patterns"):
            cmd_options.extend(["--ignore", filter_opts["ignore_patterns"]])

        if filter_opts.get("filter_mode") and filter_opts["filter_mode"] != "PUB_ONLY":
            cmd_options.extend(["--filter-mode", filter_opts["filter_mode"]])

        return cmd_options

    def _find_generated_files(self, output_name, output_format):
        """Find files generated by pyreverse"""
        generated_files = []

        # Common patterns for generated files
        patterns = [
            f"classes_{output_name}",
            f"packages_{output_name}",
            f"{output_name}_classes",
            f"{output_name}_packages",
        ]

        ext = output_format.lower().replace(".", "")

        for pattern in patterns:
            filename = f"{pattern}.{ext}"
            filepath = os.path.join(self.output_dir, filename)

            if os.path.exists(filepath):
                file_info = {
                    "name": filename,
                    "path": filepath,
                    "size": os.path.getsize(filepath),
                    "type": "classes" if "classes" in pattern else "packages",
                }
                generated_files.append(file_info)

        return generated_files

